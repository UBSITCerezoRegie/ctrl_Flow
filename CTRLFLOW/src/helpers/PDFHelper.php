.footer-note { position: absolute; bottom: 10px; width: 100%; text-align: center; font-size: 10px; color: #666; border-top:1px solid #ccc; padding-top:6px; }
</style></head>
<body><div class='container'>
  <div class='header'>Drainage Blockage Escalation Slip</div>
  <table><tr><th>Escalation Code</th><th>Escalation Date</th></tr>
