  <table><tr><th>Report Code</th><th>Barangay</th><th>Landmark</th></tr>
    <tr><td>{$safe($report['report_code'])}</td><td>{$safe($report['barangay'])}</td><td>{$safe($report['landmark'])}</td></tr></table>
