<?php
use Dompdf\Dompdf;
use Dompdf\Options;

require_once __DIR__ . '/../../vendor/autoload.php';
require_once __DIR__ . '/../models/EscalationModel.php';
require_once __DIR__ . '/../models/ReportModel.php';

class PDFHelper {

  public static function generateEscalationPDF($escalationId) {
    $esc = EscalationModel::getById($escalationId);
    if (!$esc) exit('Escalation not found');
    $report = ReportModel::getById($esc['report_id']);
    if (!$report) exit('Report not found');

    $html = self::renderEscalationHTML($esc, $report);

    $options = new Options();
    $options->set('isRemoteEnabled', true);
    $dompdf = new Dompdf($options);
    $dompdf->loadHtml($html);
    $dompdf->setPaper('A4', 'portrait');
    $dompdf->render();

    $filename = 'Escalation_' . ($esc['escalation_code'] ?? $escalationId) . '.pdf';
    $dompdf->stream($filename, ['Attachment' => false]);
    exit;
  }

