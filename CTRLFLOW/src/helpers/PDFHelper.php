  <table><tr><th>Reason for Escalation</th></tr><tr><td><pre>{$safe($esc['reason'])}</pre></td></tr>
    <tr><th>Details</th></tr><tr><td style='min-height:80px;'><pre>{$safe($esc['details'])}</pre></td></tr></table>
